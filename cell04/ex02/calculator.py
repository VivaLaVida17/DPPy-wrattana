#!/usr/bin/env python3
val1 = int(input("Give me the first number: "))
val2 = int(input("Give me the second number: "))
print("Thank you!")
print(f"{val1} + {val2} = {val1 + val2}")
print(f"{val1} - {val2} = {val1 - val2}")
print(f"{val1} / {val2} = {int(val1 / val2)}")
print(f"{val1} * {val2} = {val1 * val2}")